"""Write po/<lang>.po from po/dudes-control-center.pot and po/tools/translations.py.
English (UK) is derived from the English texts (US -> UK spelling).
Checks that every translation keeps the msgid's placeholders and markup tags."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
po_dir = os.path.dirname(here)
sys.path.insert(0, here)
from translations import T

pot = open(os.path.join(po_dir, 'dudes-control-center.pot'), encoding='utf-8').read()
entries = []                     # (block text, msgid as PO-escaped string)
for block in pot.split('\n\n'):
    m = re.search(r'^msgid ((?:"(?:[^"\\]|\\.)*"\s*)+)msgstr', block, re.M)
    if not m: continue
    msgid = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)))
    if msgid: entries.append((block, msgid))
if len(entries) != len(T):
    sys.exit(f'{len(entries)} texts in the .pot but {len(T)} translations - update translations.py')

PH = re.compile(r'%(?:\d+\$)?[-+ #0]*\d*(?:\.\d+)?[sduxf%]')
TAG = re.compile(r'</?[a-z]+')
def check(msgid, tr, lang, i):
    if 'no-c-format' not in entries[i][0] and PH.findall(msgid) != PH.findall(tr):
        sys.exit(f'{lang} #{i}: placeholders differ\n  {msgid}\n  {tr}')
    if sorted(TAG.findall(msgid)) != sorted(TAG.findall(tr)):
        sys.exit(f'{lang} #{i}: markup differs\n  {msgid}\n  {tr}')
    if msgid.count('\\n') != tr.count('\\n') and lang != 'en_GB' and '\\n' in msgid:
        sys.exit(f'{lang} #{i}: line breaks differ')

def uk(text):
    for us, gb in (('Coloring', 'Colouring'), ('coloring', 'colouring'), ('Colors', 'Colours'),
                   ('colors', 'colours'), ('Color', 'Colour'), ('color', 'colour'),
                   ('Honoring', 'Honouring'), ('honoring', 'honouring')):
        text = re.sub(r'\b' + us, gb, text)
    return text

names = {'de': 'German', 'es': 'Spanish', 'ja': 'Japanese', 'ko': 'Korean', 'en_GB': 'English (UK)'}
for col, lang in enumerate(['de', 'es', 'ja', 'ko', 'en_GB']):
    out = [f'''# {names[lang]} translation of Dudes Control Center.
# SPDX-License-Identifier: GPL-2.0-only
# Generated by po/tools/make_po.py from po/tools/translations.py.
msgid ""
msgstr ""
"Project-Id-Version: dudes-control-center\\n"
"PO-Revision-Date: 2026-11-22 00:00+0000\\n"
"Last-Translator: Claude (AI), not reviewed by a native speaker\\n"
"Language-Team: none\\n"
"Language: {lang}\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Plural-Forms: nplurals=2; plural=(n != 1);\\n"
''']
    done = 0
    for i, (block, msgid) in enumerate(entries):
        tr = uk(msgid) if lang == 'en_GB' else T[i][col]
        if not tr or tr == msgid: continue
        check(msgid, tr, lang, i)
        flags = re.findall(r'^#, .*$', block, re.M)
        out.append('\n'.join(flags + [f'msgid "{msgid}"', f'msgstr "{tr}"']) + '\n')
        done += 1
    open(os.path.join(po_dir, f'{lang}.po'), 'w', encoding='utf-8').write('\n'.join(out))
    print(f'{lang}.po: {done} translated texts')
